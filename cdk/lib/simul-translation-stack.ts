import * as path from "path";
import * as cdk from "aws-cdk-lib";
import { Construct } from "constructs";
import * as ec2 from "aws-cdk-lib/aws-ec2";
import * as ecs from "aws-cdk-lib/aws-ecs";
import * as elbv2 from "aws-cdk-lib/aws-elasticloadbalancingv2";
import * as iam from "aws-cdk-lib/aws-iam";
import * as logs from "aws-cdk-lib/aws-logs";
import * as secretsmanager from "aws-cdk-lib/aws-secretsmanager";
import * as s3 from "aws-cdk-lib/aws-s3";
import * as s3deploy from "aws-cdk-lib/aws-s3-deployment";
import * as cloudfront from "aws-cdk-lib/aws-cloudfront";
import * as origins from "aws-cdk-lib/aws-cloudfront-origins";
import * as lambda from "aws-cdk-lib/aws-lambda";
import { Platform } from "aws-cdk-lib/aws-ecr-assets";
import { loadConfig } from "./config";
import { readingsHash } from "./dictionary-dir";
import { buildLiveKitUserData } from "./livekit-user-data";

export class SimulTranslationStack extends cdk.Stack {
  constructor(scope: Construct, id: string, props?: cdk.StackProps) {
    super(scope, id, props);
    const cfg = loadConfig(this);
    const region = cdk.Stack.of(this).region;
    const retention = cfg.logRetentionDays as logs.RetentionDays;

    // ---------------------------------------------------------------- Network
    // Public subnets only, no NAT (cost/time). Security groups are the boundary.
    const vpc = new ec2.Vpc(this, "Vpc", {
      maxAzs: 2,
      natGateways: 0,
      subnetConfiguration: [{ name: "public", subnetType: ec2.SubnetType.PUBLIC, cidrMask: 24 }],
    });

    // ---------------------------------------------------------------- Secrets
    // Values are generated by Secrets Manager; only ARNs appear in the template.
    const livekitSecret = new secretsmanager.Secret(this, "LiveKitApiSecret", {
      description: "LiveKit API key/secret shared by the SFU, the publisher app and the token endpoint",
      generateSecretString: {
        secretStringTemplate: JSON.stringify({ apiKey: cfg.livekitApiKey }),
        generateStringKey: "apiSecret",
        passwordLength: 48,
        excludePunctuation: true,
      },
    });
    const srtSecret = new secretsmanager.Secret(this, "SrtPassphraseSecret", {
      description: "SRT passphrase (AES) for OBS -> app ingest",
      generateSecretString: { passwordLength: 32, excludePunctuation: true, includeSpace: false },
    });

    // ---------------------------------------------------------------- Logs
    const appLogGroup = new logs.LogGroup(this, "AppLogGroup", {
      logGroupName: "/simul-translation/app",
      retention,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });
    const livekitLogGroup = new logs.LogGroup(this, "LiveKitLogGroup", {
      logGroupName: "/simul-translation/livekit",
      retention,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });
    const tokenLogGroup = new logs.LogGroup(this, "TokenLogGroup", {
      logGroupName: "/simul-translation/token",
      retention,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });

    // ---------------------------------------------------------------- LiveKit SFU (EC2)
    const livekitEip = new ec2.CfnEIP(this, "LiveKitEip", {
      domain: "vpc",
      tags: [{ key: "Name", value: "simul-translation-livekit" }],
    });
    const livekitHost = cfg.livekitHostname || cdk.Fn.join("", [livekitEip.ref, ".sslip.io"]);
    const livekitUrl = cdk.Fn.join("", ["wss://", livekitHost]);

    // Intentionally public: browsers on any network must reach signaling and media.
    // 7880 (plain signaling), 22 and 80 are never opened.
    const livekitSg = new ec2.SecurityGroup(this, "LiveKitSg", {
      vpc,
      description: "LiveKit SFU: WSS 443 (Caddy), ICE/TCP, WebRTC UDP range",
      allowAllOutbound: true,
    });
    livekitSg.addIngressRule(ec2.Peer.anyIpv4(), ec2.Port.tcp(443), "WSS signaling via Caddy + ACME TLS-ALPN (public)");
    livekitSg.addIngressRule(ec2.Peer.anyIpv4(), ec2.Port.tcp(cfg.livekitTcpPort), "WebRTC ICE/TCP fallback (public)");
    livekitSg.addIngressRule(
      ec2.Peer.anyIpv4(),
      ec2.Port.udpRange(cfg.livekitUdpPortStart, cfg.livekitUdpPortEnd),
      "WebRTC media UDP (public)",
    );

    const livekitRole = new iam.Role(this, "LiveKitInstanceRole", {
      assumedBy: new iam.ServicePrincipal("ec2.amazonaws.com"),
      managedPolicies: [iam.ManagedPolicy.fromAwsManagedPolicyName("AmazonSSMManagedInstanceCore")],
    });
    livekitSecret.grantRead(livekitRole);
    livekitLogGroup.grantWrite(livekitRole);

    const instanceType = new ec2.InstanceType(cfg.livekitInstanceType);
    const cpuType =
      instanceType.architecture === ec2.InstanceArchitecture.ARM_64
        ? ec2.AmazonLinuxCpuType.ARM_64
        : ec2.AmazonLinuxCpuType.X86_64;

    const livekitInstance = new ec2.Instance(this, "LiveKitInstance", {
      vpc,
      vpcSubnets: { subnetType: ec2.SubnetType.PUBLIC },
      instanceType,
      machineImage: ec2.MachineImage.latestAmazonLinux2023({ cpuType }),
      securityGroup: livekitSg,
      role: livekitRole,
      requireImdsv2: true,
      associatePublicIpAddress: true,
      userDataCausesReplacement: true,
      blockDevices: [
        {
          deviceName: "/dev/xvda",
          volume: ec2.BlockDeviceVolume.ebs(20, { volumeType: ec2.EbsDeviceVolumeType.GP3, encrypted: true }),
        },
      ],
      userData: buildLiveKitUserData({
        region,
        livekitSecretArn: livekitSecret.secretArn,
        publicIp: livekitEip.ref,
        hostname: livekitHost,
        logGroupName: livekitLogGroup.logGroupName,
        livekitImage: cfg.livekitImage,
        caddyImage: cfg.caddyImage,
        tcpPort: cfg.livekitTcpPort,
        udpPortStart: cfg.livekitUdpPortStart,
        udpPortEnd: cfg.livekitUdpPortEnd,
      }),
    });
    cdk.Tags.of(livekitInstance).add("Name", "simul-translation-livekit");

    const livekitEipAssoc = new ec2.CfnEIPAssociation(this, "LiveKitEipAssoc", {
      allocationId: livekitEip.attrAllocationId,
      instanceId: livekitInstance.instanceId,
    });

    // ---------------------------------------------------------------- App (Fargate)
    const cluster = new ecs.Cluster(this, "Cluster", { vpc });

    const taskDef = new ecs.FargateTaskDefinition(this, "AppTask", {
      cpu: cfg.taskCpu,
      memoryLimitMiB: cfg.taskMemoryMiB,
      runtimePlatform: {
        cpuArchitecture: ecs.CpuArchitecture.ARM64,
        operatingSystemFamily: ecs.OperatingSystemFamily.LINUX,
      },
    });
    // Least privilege: only the three streaming/AI calls the app makes.
    // These actions have no useful resource-level scoping for this use case.
    // Language identification (languageFilter=langid) is a parameter of
    // StartStreamTranscription and needs no additional action.
    taskDef.taskRole.addToPrincipalPolicy(
      new iam.PolicyStatement({
        actions: ["transcribe:StartStreamTranscription", "translate:TranslateText", "polly:SynthesizeSpeech"],
        resources: ["*"],
      }),
    );

    // Optional LLM engine (translateEngine=llm): Bedrock InvokeModel (Converse, non-streaming) on the
    // Japan inference profile and its two destination foundation models only, plus read access to the
    // Translate terminology the glossary is loaded from. Nothing is added for the default engine.
    // No wildcard resources; InvokeModelWithResponseStream is not granted (ConverseStream is not used).
    if (cfg.translateEngine === "llm") {
      const foundationModelId = cfg.llmModelId.replace(/^jp\./, "");
      taskDef.taskRole.addToPrincipalPolicy(
        new iam.PolicyStatement({
          actions: ["bedrock:InvokeModel"],
          resources: [
            `arn:aws:bedrock:${this.region}:${this.account}:inference-profile/${cfg.llmModelId}`,
            `arn:aws:bedrock:ap-northeast-1::foundation-model/${foundationModelId}`,
            `arn:aws:bedrock:ap-northeast-3::foundation-model/${foundationModelId}`,
          ],
        }),
      );
      taskDef.taskRole.addToPrincipalPolicy(
        new iam.PolicyStatement({
          actions: ["translate:GetTerminology"],
          resources: [
            `arn:aws:translate:${this.region}:${this.account}:terminology/${cfg.translateTerminologyName}`,
            `arn:aws:translate:${this.region}:${this.account}:terminology/${cfg.translateTerminologyName}/*`,
          ],
        }),
      );
    }

    // Every variable read by app/src/config.ts and src/main.ts (INPUT_FILE and
    // FFMPEG_PATH intentionally unset). Secrets are injected by ECS via the execution role.
    taskDef.addContainer("app", {
      containerName: "app",
      image: ecs.ContainerImage.fromAsset(path.resolve(__dirname, "..", cfg.appPath), {
        platform: Platform.LINUX_ARM64,
        // The Polly readings come from the resolved dictionary folder (see app/Dockerfile).
        buildContexts: { dictionary: cfg.dictionaryDir },
        // buildContexts hashes only the path; add the file content so a changed dictionary makes a new image.
        extraHash: readingsHash(path.join(cfg.dictionaryDir, "polly-readings.csv")),
        invalidation: { buildContexts: false },
      }),
      logging: ecs.LogDrivers.awsLogs({ logGroup: appLogGroup, streamPrefix: "app" }),
      stopTimeout: cdk.Duration.seconds(10),
      environment: {
        AWS_REGION: region,
        LOG_LEVEL: cfg.logLevel,
        SRT_HOST: "0.0.0.0", // in-task bind (awsvpc); SGs restrict who can reach it
        SRT_PORT: String(cfg.srtPort),
        SRT_LATENCY_MS: String(cfg.srtLatencyMs),
        SRT_LISTEN_TIMEOUT_SEC: String(cfg.srtListenTimeoutSec),
        SRT_ANALYZE_MS: String(cfg.srtAnalyzeMs),
        SAMPLE_RATE: String(cfg.sampleRate),
        FRAME_BYTES: String(cfg.frameBytes),
        SOURCE_LANGUAGE: cfg.sourceLanguage,
        TRANSCRIBE_VOCABULARY: cfg.transcribeVocabularyName,
        PARTIAL_STABILITY: cfg.partialStability,
        LANGUAGE_FILTER: cfg.languageFilter,
        LANGUAGE_OPTIONS: cfg.languageOptions,
        LANGID_SETTLE_WORDS: String(cfg.langidSettleWords),
        LANGID_SETTLE_MODE: cfg.langidSettleMode,
        LANGID_SETTLE_WORDS_DEFAULT: String(cfg.langidSettleWordsDefault),
        LANGID_SETTLE_WORDS_AFTER_JA: String(cfg.langidSettleWordsAfterJa),
        LANGID_JA_MEMORY_MS: String(cfg.langidJaMemoryMs),
        LANGID_SHORT_WORDS: String(cfg.langidShortWords),
        LANGID_SHORT_MIN_CONF: String(cfg.langidShortMinConf),
        SEGMENTATION_MODE: cfg.segmentationMode,
        CHUNK_MIN_WORDS: String(cfg.chunkMinWords),
        CHUNK_MAX_WORDS: String(cfg.chunkMaxWords),
        CHUNK_MAX_MS: String(cfg.chunkMaxMs),
        CHUNK_PAUSE_MS: String(cfg.chunkPauseMs),
        CHUNK_CONJUNCTIONS: cfg.chunkConjunctions,
        MERGE_SHORT: cfg.mergeShort,
        SENTENCE_MIN_WORDS: String(cfg.sentenceMinWords),
        SENTENCE_COMPLETE_WORDS: String(cfg.sentenceCompleteWords),
        MERGE_PAUSE_MS: String(cfg.mergePauseMs),
        MERGE_MAX_HOLD_MS: String(cfg.mergeMaxHoldMs),
        DANGLING_GUARD: cfg.danglingGuard,
        DANGLING_WORDS: cfg.danglingWords,
        DANGLING_MAX_WORDS: String(cfg.danglingMaxWords),
        DANGLING_MAX_HOLD_MS: String(cfg.danglingMaxHoldMs),
        CUT_LOOKAHEAD_MS: String(cfg.cutLookaheadMs),
        SHORT_SENTENCE_JOIN: cfg.shortSentenceJoin,
        SHORT_SENTENCE_WORDS: String(cfg.shortSentenceWords),
        SHORT_JOIN_PAUSE_MS: String(cfg.shortJoinPauseMs),
        SPEEDUP_STEPS: cfg.speedupSteps || "off",
        MAX_BACKLOG_MS: String(cfg.maxBacklogMs),
        SPEED_MODE: cfg.speedMode,
        SPEED_LEVELS: cfg.speedLevels,
        SPEED_THRESHOLDS_MS: cfg.speedThresholdsMs,
        SPEED_HYSTERESIS_MS: String(cfg.speedHysteresisMs),
        SPEED_HOLD_MS: String(cfg.speedHoldMs),
        SPEED_URGENT_MS: String(cfg.speedUrgentMs),
        SPEED_LOOKAHEAD: String(cfg.speedLookahead),
        SPEED_MS_PER_CHAR: String(cfg.speedMsPerChar),
        SPEED_RESET_GAP_MS: String(cfg.speedResetGapMs),
        FILLER_FILTER: cfg.fillerFilter,
        FILLER_WORDS: cfg.fillerWords,
        FILLER_PHRASES: cfg.fillerPhrases,
        JA_FILLER_PATTERNS: cfg.jaFillerPatterns,
        ENABLE_CORRECTION: cfg.enableCorrection,
        TRANSLATE_SOURCE: cfg.translateSource,
        TRANSLATE_TARGET: cfg.translateTarget,
        TRANSLATE_FORMALITY: cfg.translateFormality,
        TRANSLATE_TERMINOLOGY: cfg.translateTerminologyName,
        TRANSLATE_ENGINE: cfg.translateEngine,
        LLM_MODEL_ID: cfg.llmModelId,
        LLM_TIMEOUT_MS: String(cfg.llmTimeoutMs),
        LLM_CONTEXT_CHUNKS: String(cfg.llmContextChunks),
        LLM_CONTEXT_RESET_MS: String(cfg.llmContextResetMs),
        LLM_GLOSSARY: cfg.llmGlossary,
        LLM_MAX_TOKENS: String(cfg.llmMaxTokens),
        LLM_BREAKER_MS: String(cfg.llmBreakerMs),
        LLM_SKIP_BACKLOG_MS: String(cfg.llmSkipBacklogMs),
        LLM_PARALLEL_FALLBACK: cfg.llmParallelFallback,
        LLM_MAX_CHARS_PER_WORD: String(cfg.llmMaxCharsPerWord),
        LLM_KEEPWARM_MS: String(cfg.llmKeepWarmMs),
        LLM_PROMPT_VERSION: String(cfg.llmPromptVersion),
        LATENCY_PRESET: cfg.latencyPreset,
        POLLY_VOICE: cfg.pollyVoice,
        POLLY_ENGINE: cfg.pollyEngine,
        POLLY_SAMPLE_RATE: String(cfg.pollySampleRate),
        POLLY_READINGS: cfg.pollyReadings,
        CAPTIONS: cfg.captions,
        CAPTIONS_JA_SPEECH: cfg.captionsJapaneseSpeech,
        LIVEKIT_URL: livekitUrl,
        LIVEKIT_ROOM: cfg.roomName,
        LIVEKIT_TOKEN_TTL: cfg.publisherTokenTtl,
        HEALTH_PORT: String(cfg.healthPort),
        HEALTH_HOST: "0.0.0.0", // NLB health check (awsvpc; SGs restrict who can reach it); app default is loopback
      },
      secrets: {
        SRT_PASSPHRASE: ecs.Secret.fromSecretsManager(srtSecret),
        LIVEKIT_API_KEY: ecs.Secret.fromSecretsManager(livekitSecret, "apiKey"),
        LIVEKIT_API_SECRET: ecs.Secret.fromSecretsManager(livekitSecret, "apiSecret"),
      },
      portMappings: [
        { containerPort: cfg.srtPort, protocol: ecs.Protocol.UDP },
        { containerPort: cfg.healthPort, protocol: ecs.Protocol.TCP },
      ],
    });

    const appSg = new ec2.SecurityGroup(this, "AppSg", {
      vpc,
      description: "Fargate app: SRT from venue via NLB, health check from NLB",
      allowAllOutbound: true, // AWS APIs, ECR, LiveKit wss/UDP
    });

    const service = new ecs.FargateService(this, "AppService", {
      cluster,
      taskDefinition: taskDef,
      desiredCount: cfg.desiredCount,
      assignPublicIp: true, // no NAT; egress only, inbound restricted by AppSg
      vpcSubnets: { subnetType: ec2.SubnetType.PUBLIC },
      securityGroups: [appSg],
      // Single publisher identity in LiveKit: never run two tasks at once.
      minHealthyPercent: 0,
      maxHealthyPercent: 100,
      // Fail a bad deploy in minutes (not ~3 h) and roll back to the last working task definition.
      circuitBreaker: { enable: true, rollback: true },
      healthCheckGracePeriod: cdk.Duration.seconds(60),
    });
    // The app needs LiveKit reachable at its EIP hostname.
    service.node.addDependency(livekitEipAssoc);

    // ---------------------------------------------------------------- SRT ingest (NLB + static EIPs)
    const nlbSg = new ec2.SecurityGroup(this, "NlbSg", {
      vpc,
      description: "SRT ingest NLB: UDP from venue CIDR(s) only",
      allowAllOutbound: false,
    });
    for (const cidr of cfg.venueCidrs) {
      nlbSg.addIngressRule(ec2.Peer.ipv4(cidr), ec2.Port.udp(cfg.srtPort), `SRT from venue ${cidr}`);
      // UDP to IP targets preserves the client IP, so the task SG must also allow the venue.
      appSg.addIngressRule(ec2.Peer.ipv4(cidr), ec2.Port.udp(cfg.srtPort), `SRT from venue ${cidr} (client IP preserved)`);
    }
    service.connections.allowFrom(nlbSg, ec2.Port.udp(cfg.srtPort), "SRT forwarded by NLB");
    service.connections.allowFrom(nlbSg, ec2.Port.tcp(cfg.healthPort), "NLB TCP health check");

    const nlbEips = vpc.publicSubnets.map(
      (_, i) =>
        new ec2.CfnEIP(this, `SrtEip${i + 1}`, {
          domain: "vpc",
          tags: [{ key: "Name", value: `simul-translation-srt-${i + 1}` }],
        }),
    );
    const nlb = new elbv2.NetworkLoadBalancer(this, "SrtNlb", {
      vpc,
      internetFacing: true,
      crossZoneEnabled: true,
      securityGroups: [nlbSg],
      subnetMappings: vpc.publicSubnets.map((subnet, i) => ({
        subnet,
        allocationId: nlbEips[i].attrAllocationId,
      })),
    });
    const listener = nlb.addListener("SrtListener", {
      port: cfg.srtPort,
      protocol: elbv2.Protocol.UDP,
    });
    listener.addTargets("SrtTargets", {
      port: cfg.srtPort,
      protocol: elbv2.Protocol.UDP,
      deregistrationDelay: cdk.Duration.seconds(5),
      targets: [
        service.loadBalancerTarget({
          containerName: "app",
          containerPort: cfg.srtPort,
          protocol: ecs.Protocol.UDP,
        }),
      ],
      // UDP cannot be health-checked directly; the app's TCP health server is used.
      healthCheck: {
        protocol: elbv2.Protocol.TCP,
        port: String(cfg.healthPort),
        interval: cdk.Duration.seconds(10),
        healthyThresholdCount: 2,
        unhealthyThresholdCount: 2,
      },
    });

    // ---------------------------------------------------------------- Listener web + token endpoint
    // Intentionally public (anonymous attendees). The token endpoint only issues
    // subscribe-only tokens; S3 stays private behind CloudFront OAC; the function URL
    // requires IAM (SigV4) so only CloudFront (OAC) can invoke it.
    const tokenFn = new lambda.Function(this, "TokenFunction", {
      runtime: lambda.Runtime.NODEJS_22_X,
      architecture: lambda.Architecture.ARM_64,
      handler: "index.handler",
      code: lambda.Code.fromAsset(path.join(__dirname, "..", "lambda", "token")),
      memorySize: 128,
      timeout: cdk.Duration.seconds(5),
      logGroup: tokenLogGroup,
      environment: {
        SECRET_ARN: livekitSecret.secretArn,
        ROOM_NAME: cfg.roomName,
        TOKEN_TTL_SEC: String(cfg.listenerTokenTtlSec),
      },
    });
    livekitSecret.grantRead(tokenFn);
    const tokenUrl = tokenFn.addFunctionUrl({ authType: lambda.FunctionUrlAuthType.AWS_IAM });

    const siteBucket = new s3.Bucket(this, "SiteBucket", {
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      encryption: s3.BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      objectOwnership: s3.ObjectOwnership.BUCKET_OWNER_ENFORCED,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
      autoDeleteObjects: true,
    });

    const distribution = new cloudfront.Distribution(this, "SiteDistribution", {
      comment: "simul-translation listener page",
      defaultRootObject: "index.html",
      priceClass: cloudfront.PriceClass.PRICE_CLASS_200,
      defaultBehavior: {
        origin: origins.S3BucketOrigin.withOriginAccessControl(siteBucket),
        viewerProtocolPolicy: cloudfront.ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
        responseHeadersPolicy: cloudfront.ResponseHeadersPolicy.SECURITY_HEADERS,
      },
      additionalBehaviors: {
        "/token": {
          origin: origins.FunctionUrlOrigin.withOriginAccessControl(tokenUrl),
          viewerProtocolPolicy: cloudfront.ViewerProtocolPolicy.HTTPS_ONLY,
          allowedMethods: cloudfront.AllowedMethods.ALLOW_GET_HEAD,
          cachePolicy: cloudfront.CachePolicy.CACHING_DISABLED,
          originRequestPolicy: cloudfront.OriginRequestPolicy.ALL_VIEWER_EXCEPT_HOST_HEADER,
          responseHeadersPolicy: cloudfront.ResponseHeadersPolicy.SECURITY_HEADERS,
        },
      },
    });
    // CloudFront OAC -> function URL also needs lambda:InvokeFunction (scoped to this distribution).
    tokenFn.addPermission("AllowCloudFrontInvokeFunction", {
      principal: new iam.ServicePrincipal("cloudfront.amazonaws.com"),
      action: "lambda:InvokeFunction",
      sourceArn: this.formatArn({
        service: "cloudfront",
        region: "",
        resource: "distribution",
        resourceName: distribution.distributionId,
      }),
      invokedViaFunctionUrl: true,
    });

    new s3deploy.BucketDeployment(this, "SiteDeployment", {
      destinationBucket: siteBucket,
      sources: [
        s3deploy.Source.asset(path.resolve(__dirname, "..", cfg.appPath, "web"), { exclude: ["local-test.html"] }),
        s3deploy.Source.jsonData("config.json", { livekitUrl, tokenEndpoint: "/token", captions: cfg.captions === "on" }),
      ],
      distribution,
      distributionPaths: ["/*"],
    });

    // ---------------------------------------------------------------- Outputs (no secret values)
    const out = (id: string, value: string, description?: string) =>
      new cdk.CfnOutput(this, id, { value, description });
    out("SrtIngestIp1", nlbEips[0].ref, "Static IP for OBS SRT (either IP works)");
    if (nlbEips[1]) out("SrtIngestIp2", nlbEips[1].ref, "Second static IP for OBS SRT");
    out("SrtPort", String(cfg.srtPort));
    out(
      "ObsSrtUrlTemplate",
      cdk.Fn.join("", [
        "srt://",
        nlbEips[0].ref,
        `:${cfg.srtPort}?mode=caller&latency=${cfg.srtLatencyMs * 1000}&pbkeylen=16&passphrase=<SRT_PASSPHRASE>`,
      ]),
      "Replace <SRT_PASSPHRASE> with the value from GetSrtPassphraseCommand",
    );
    out("SrtPassphraseSecretArn", srtSecret.secretArn);
    out(
      "GetSrtPassphraseCommand",
      cdk.Fn.join("", [
        `aws secretsmanager get-secret-value --region ${region} --secret-id `,
        srtSecret.secretArn,
        " --query SecretString --output text",
      ]),
    );
    out("LiveKitUrl", livekitUrl);
    out("LiveKitPublicIp", livekitEip.ref);
    out("LiveKitInstanceId", livekitInstance.instanceId);
    out("LiveKitApiSecretArn", livekitSecret.secretArn);
    out("ListenerUrl", cdk.Fn.join("", ["https://", distribution.distributionDomainName, "/"]));
    out("AppLogGroupName", appLogGroup.logGroupName);
    out("LiveKitLogGroupName", livekitLogGroup.logGroupName);
    out("EcsClusterName", cluster.clusterName);
    out("EcsServiceName", service.serviceName);
    out(
      "DictionaryNames",
      `vocabulary=${cfg.transcribeVocabularyName || "(none)"} terminology=${cfg.translateTerminologyName || "(none)"}`,
    );
  }
}
